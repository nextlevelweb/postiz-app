import { PrismaRepository } from '@gitroom/nestjs-libraries/database/prisma/prisma.service';
import { Injectable } from '@nestjs/common';

// Everything a connection may show: never the sealed credential, which only
// getSealedCredentialForResolver reads
const CONNECTION_SUMMARY = {
  id: true,
  name: true,
  provider: true,
  defaultModel: true,
  disabledAt: true,
  credentialUpdatedAt: true,
  lastValidatedAt: true,
  lastValidationStatus: true,
  lastValidationCode: true,
  createdById: true,
  createdAt: true,
  updatedAt: true,
} as const;

// Every query filters on organizationId itself, so a connection of another
// organization reads exactly like a missing one (null or count 0). Archived
// connections are gone for good: their credential is wiped in the same write
// and nothing reads or changes them. The provider is never changed and
// nothing is deleted
@Injectable()
export class ContentStudioAIConnectionRepository {
  constructor(
    private _connection: PrismaRepository<'contentStudioAIConnection'>
  ) {}

  // The id is generated by the caller: the credential is sealed for it first
  createConnection(input: {
    id: string;
    organizationId: string;
    name: string;
    provider: string;
    sealedCredential: string;
    defaultModel: string | null;
    credentialUpdatedAt: Date;
    createdById: string;
  }) {
    return this._connection.model.contentStudioAIConnection.create({
      data: {
        id: input.id,
        organizationId: input.organizationId,
        name: input.name,
        provider: input.provider,
        sealedCredential: input.sealedCredential,
        defaultModel: input.defaultModel,
        credentialUpdatedAt: input.credentialUpdatedAt,
        createdById: input.createdById,
      },
      select: CONNECTION_SUMMARY,
    });
  }

  listConnectionsForOrganization(organizationId: string) {
    return this._connection.model.contentStudioAIConnection.findMany({
      where: {
        organizationId,
        archivedAt: null,
      },
      // id breaks ties, so the order is stable
      orderBy: [{ name: 'asc' }, { id: 'asc' }],
      select: CONNECTION_SUMMARY,
    });
  }

  getConnectionForOrganization(organizationId: string, id: string) {
    return this._connection.model.contentStudioAIConnection.findFirst({
      where: {
        id,
        organizationId,
        archivedAt: null,
      },
      select: CONNECTION_SUMMARY,
    });
  }

  // A field left undefined is left unchanged; defaultModel null removes it.
  // The value must already be checked by the caller
  updateConnectionMetadata(input: {
    organizationId: string;
    connectionId: string;
    name?: string;
    defaultModel?: string | null;
  }) {
    return this._connection.model.contentStudioAIConnection.updateMany({
      where: {
        id: input.connectionId,
        organizationId: input.organizationId,
        archivedAt: null,
      },
      data: {
        name: input.name,
        defaultModel: input.defaultModel,
      },
    });
  }

  // Overwrites the envelope with a new one sealed by the caller; the old one
  // is never opened. A new credential has not been tested yet
  replaceCredential(input: {
    organizationId: string;
    connectionId: string;
    sealedCredential: string;
    credentialUpdatedAt: Date;
  }) {
    return this._connection.model.contentStudioAIConnection.updateMany({
      where: {
        id: input.connectionId,
        organizationId: input.organizationId,
        archivedAt: null,
      },
      data: {
        sealedCredential: input.sealedCredential,
        credentialUpdatedAt: input.credentialUpdatedAt,
        lastValidatedAt: null,
        lastValidationStatus: null,
        lastValidationCode: null,
      },
    });
  }

  disableConnection(organizationId: string, id: string, disabledAt: Date) {
    return this._connection.model.contentStudioAIConnection.updateMany({
      where: {
        id,
        organizationId,
        archivedAt: null,
        disabledAt: null,
      },
      data: {
        disabledAt,
      },
    });
  }

  enableConnection(organizationId: string, id: string) {
    return this._connection.model.contentStudioAIConnection.updateMany({
      where: {
        id,
        organizationId,
        archivedAt: null,
        disabledAt: { not: null },
      },
      data: {
        disabledAt: null,
      },
    });
  }

  // Removal: the credential leaves the database in the same write that
  // archives the row, which stays for the history that refers to it
  archiveConnection(organizationId: string, id: string, archivedAt: Date) {
    return this._connection.model.contentStudioAIConnection.updateMany({
      where: {
        id,
        organizationId,
        archivedAt: null,
      },
      data: {
        archivedAt,
        sealedCredential: null,
      },
    });
  }

  // The only read of the sealed credential, for the provider resolver. The
  // caller still has to refuse a disabled connection
  getSealedCredentialForResolver(organizationId: string, id: string) {
    return this._connection.model.contentStudioAIConnection.findFirst({
      where: {
        id,
        organizationId,
        archivedAt: null,
      },
      select: {
        id: true,
        provider: true,
        sealedCredential: true,
        disabledAt: true,
      },
    });
  }
}
